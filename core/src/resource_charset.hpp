inline Bytes text_bytes(const std::string& text) {
 Bytes out;for(auto cp:scalars(text)) {
  if(cp<128)out.push_back(cp);
  else {auto found=std::find(cp437.begin(),cp437.end(),cp);if(found==cp437.end())throw std::runtime_error("resource JSON: text is not representable in CP437");out.push_back(128+std::distance(cp437.begin(),found));}
 }return out;
}
