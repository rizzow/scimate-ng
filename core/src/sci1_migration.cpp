void append_byte_instruction(Bytes& code, unsigned opcode, std::initializer_list<unsigned> operands) {
    code.push_back(static_cast<std::uint8_t>(sci_vm::encoded_opcode(opcode,operands.size() != 0)));
    for (const auto value : operands) {
        if (value > 255) throw std::runtime_error("generated byte operand exceeds VM encoding");
        code.push_back(static_cast<std::uint8_t>(value));
    }
}
void put(Bytes& bytes, unsigned value) { binary_detail::append(bytes, value, 2, "migration address outside 16-bit script"); }
void patch(Bytes& bytes, std::size_t offset, unsigned value) {
    binary_detail::patch_word(bytes, offset, value, "migration address outside 16-bit script");
}
// This is a ScummVM compatibility profile, not a native SCI1 sound port.
// Validate the source ABI and resource encoding independently of the runtime
// dispatch guard. ScummVM selects SCI0 late sound when nodePtr is absent.
void validate_sound_dispatch(const Game& game) {
    const Bytes* selectors = nullptr;
    for (const auto& resource : game.resources) {
        if (resource.entry.id.type == ResourceType::vocab && resource.entry.id.number == 997 && !selectors)
            selectors = &resource.payload;
    }
    if (!selectors) throw std::runtime_error("SCI0 sound compatibility requires selector vocabulary 997 to verify ScummVM dispatch");
    const auto names = vocabulary_detail::read_names(*selectors, true);
    for (const auto& name : names.entries)
        if (name && std::string(name->begin(), name->end()) == "nodePtr")
            throw std::runtime_error("SCI0 sound compatibility cannot preserve late sound dispatch with nodePtr present; early sound needs a semantic port");
    std::set<std::uint16_t> seen_sounds;
    for (const auto& resource : game.resources) if (resource.entry.id.type == ResourceType::sound &&
                                                  seen_sounds.insert(resource.entry.id.number).second) {
        try {
            const auto sound = read_sci0_sound(resource.payload);
            if (sound.header[0] == 2 && sound.sample_header.empty())
                throw std::runtime_error("sample flag set without a digital sample header");
        }
        catch (const std::exception& error) {
            throw std::runtime_error("sound " + std::to_string(resource.entry.id.number) + ": " + error.what());
        }
    }
}
void validate_sound_call(const ParsedScript& parsed, std::size_t index) {
    const auto& call = parsed.instructions.at(index);
    const auto frame = call.operands.at(1);
    if (frame < 2 || frame > 6 || frame % 2)
        throw std::runtime_error("unsupported SCI0 DoSound argument frame at " + std::to_string(call.start));
    // Walk a contiguous, side-effect-free push sequence. Never infer a subop
    // from the nearest pushi: object arguments may also use immediate values.
    std::vector<int> pushed;
    auto cursor = call.start;
    const auto needed = frame/2+1; // Includes the argument-count stack word.
    while (pushed.size() < needed && index > 0) {
        const auto& inst = parsed.instructions.at(--index);
        bool noop_jump = inst.opcode == op::jump && target(inst) == inst.end;
        if (noop_jump) for (const auto& other : parsed.instructions)
            if (other.start != inst.start && (op::is_branch(other.opcode) || other.opcode == op::call_local) && target(other) == cursor)
                noop_jump = false;
        if (inst.end != cursor || (parsed.labels.count(cursor) && !noop_jump) || parsed.procedures.count(cursor)) break;
        cursor = inst.start;
        int value = -1;
        if (inst.opcode == op::push_immediate) value = static_cast<int>(inst.operands.at(0));
        else if (inst.opcode >= op::push_zero && inst.opcode <= op::push_two) value = static_cast<int>(inst.opcode-op::push_zero);
        else if (inst.opcode == op::push_accumulator || inst.opcode == op::property_to_stack ||
                 inst.opcode == op::increment_property_to_stack || inst.opcode == op::decrement_property_to_stack ||
                 inst.opcode == op::load_offset_to_stack || inst.opcode == op::push_self ||
                 (inst.opcode >= op::load_global_to_stack && inst.opcode <= op::load_parameter_to_stack)) {}
        // Unary accumulator operations do not consume any stack words. The
        // computed argument remains unknown, while earlier frame constants
        // remain available for independent count/suboperation validation.
        else if (noop_jump || op::is_accumulator_unary(inst.opcode) || inst.opcode == op::load_immediate || inst.opcode == op::load_class || inst.opcode == op::self_id ||
                 inst.opcode == op::property_to_accumulator || inst.opcode == op::load_offset_to_accumulator ||
                 (inst.opcode >= op::load_global_to_accumulator && inst.opcode <= op::load_parameter_to_accumulator)) continue;
        else break;
        pushed.push_back(value);
    }
    if (pushed.size() != needed || pushed.back() != static_cast<int>(frame/2))
        throw std::runtime_error("SCI0 DoSound frame cannot be proven statically at " + std::to_string(call.start));
    const auto subop = pushed.at(pushed.size()-2);
    constexpr std::array<unsigned,13> min_args{2,2,1,2,1,2,2,1,1,2,2,1,1};
    constexpr std::array<unsigned,13> max_args{2,2,2,2,2,2,2,1,2,2,2,1,1};
    if (subop < 0 || subop > 12 || frame/2 < min_args.at(static_cast<unsigned>(subop)) ||
        frame/2 > max_args.at(static_cast<unsigned>(subop)))
        throw std::runtime_error("unsupported SCI0 DoSound suboperation/frame at " + std::to_string(call.start));
}
ParsedScript parse_migration_script(const Resource& resource) {
    try {
        // Only script 0 changes layout. Other scripts retain every instruction
        // address, allowing legacy conditional/jump operands to pass through
        // verbatim without claiming their runtime paths are safe.
        auto parsed = parse(resource.payload,resource.entry.id.number == 0,false);
        for (const auto& inst : parsed.instructions)
            if (inst.opcode == op::call_local && !parsed.boundaries.count(target(inst)))
                throw std::runtime_error("local call at byte " + std::to_string(inst.start) + " does not target a decoded instruction");
        return parsed;
    }
    catch (const std::exception& error) {
        throw std::runtime_error("script " + std::to_string(resource.entry.id.number) + ": " + error.what());
    }
}
bool select_missing_script_fallback(Resource& resource, const ParsedScript& parsed,
                                    const Instruction& call, std::string& note) {
    if (call.opcode != op::call_external) return false;
    for (std::size_t g = 0; g+1 < parsed.instructions.size(); ++g) {
        const auto& load = parsed.instructions[g];
        const auto& branch = parsed.instructions[g+1];
        if (load.opcode != op::load_global_to_accumulator || branch.opcode != op::branch_false || load.end != branch.start || parsed.procedures.count(branch.start)) continue;
        const auto fallback = target(branch);
        if (branch.end > call.start || fallback <= call.end || !parsed.boundaries.count(fallback)) continue;
        std::size_t last = g+2;
        auto cursor = branch.end;
        bool valid = true, saw_call = false;
        for (; last < parsed.instructions.size() && parsed.instructions[last].start < fallback; ++last) {
            const auto& inst = parsed.instructions[last];
            if (inst.start != cursor || parsed.procedures.count(inst.start)) { valid = false; break; }
            cursor = inst.end;
            if (inst.start == call.start) { saw_call = true; continue; }
            if (inst.opcode == op::jump && inst.end == fallback && saw_call) continue;
            // The optional arm may prepare arguments, then call, then jump.
            // Disable no additional work or unrelated side effects.
            if (saw_call || !(inst.opcode == op::push_accumulator || inst.opcode == op::push_immediate || inst.opcode == op::property_to_stack ||
                inst.opcode == op::load_offset_to_stack || (inst.opcode >= op::push_zero && inst.opcode <= op::push_self) ||
                (inst.opcode >= op::load_global_to_stack && inst.opcode <= op::load_parameter_to_stack))) { valid = false; break; }
        }
        if (!valid || !saw_call || cursor != fallback || last == g+2) continue;
        const auto& jump = parsed.instructions[last-1];
        if (jump.opcode != op::jump || target(jump) <= fallback || !parsed.boundaries.count(target(jump))) continue;
        const auto merge = target(jump);
        bool fallback_call = false;
        cursor = fallback;
        for (auto i = last; i < parsed.instructions.size() && parsed.instructions[i].start < merge; ++i) {
            const auto& inst = parsed.instructions[i];
            if (inst.start != cursor || op::is_branch(inst.opcode) || inst.opcode == op::return_) { valid = false; break; }
            cursor = inst.end;
            if (inst.opcode == op::call_kernel || inst.opcode == op::call_base || inst.opcode == op::call_external || inst.opcode == op::send ||
                inst.opcode == op::send_self || inst.opcode == op::send_super) fallback_call = true;
        }
        if (!valid || cursor != merge || !fallback_call) continue;
        // An alternate entry into the disabled arm would invalidate the proof.
        for (const auto& inst : parsed.instructions) if (op::is_branch(inst.opcode) || inst.opcode == op::call_local) {
            const auto destination = target(inst);
            if (destination == branch.start || (destination >= branch.end && destination < fallback)) { valid = false; break; }
        }
        if (!valid) continue;
        // LDI has the same operand width/extent as LAG. Loading zero proves BNT
        // takes the existing fallback and preserves its accumulator semantics.
        resource.payload.at(load.start) = static_cast<std::uint8_t>((op::load_immediate << 1) | (resource.payload.at(load.start) & 1u));
        resource.payload.at(load.start+1) = 0;
        if (load.width == 2) resource.payload.at(load.start+2) = 0;
        note = "script " + std::to_string(resource.entry.id.number) + " at byte " + std::to_string(call.start) +
            ": missing optional script " + std::to_string(call.operands.at(0)) + "; global " +
            std::to_string(load.operands.at(0)) + " guard specialized to existing fallback at byte " + std::to_string(fallback);
        return true;
    }
    return false;
}
std::map<std::uint16_t,ParsedScript> validate_migration_scripts(Resources& resources, std::vector<std::string>& fallbacks) {
    std::map<std::uint16_t,ParsedScript> scripts;
    for (const auto& entry : resources) if (entry.first.first == ResourceType::script)
        scripts.emplace(entry.first.second,parse_migration_script(entry.second));
    for (const auto& entry : scripts) for (const auto& inst : entry.second.instructions) {
        if (inst.opcode != op::call_base && inst.opcode != op::call_external) continue;
        const auto script_number = inst.opcode == op::call_base ? 0u : inst.operands.at(0);
        const auto export_number = inst.operands.at(inst.opcode == op::call_base ? 0 : 1);
        const auto destination = scripts.find(static_cast<std::uint16_t>(script_number));
        const auto context = "script " + std::to_string(entry.first) + " at byte " + std::to_string(inst.start) +
                             ": direct call to script " + std::to_string(script_number) + " export " + std::to_string(export_number);
        if (destination == scripts.end()) {
            std::string note;
            if (select_missing_script_fallback(resources.at({ResourceType::script,entry.first}),entry.second,inst,note)) {
                fallbacks.push_back(std::move(note));
                continue;
            }
            throw std::runtime_error(context + " targets a missing script without a verified fallback");
        }
        if (export_number >= destination->second.exports.size()) throw std::runtime_error(context + " has no export slot");
        if (!destination->second.boundaries.count(destination->second.exports.at(export_number).second))
            throw std::runtime_error(context + " does not target a decoded instruction");
    }
    for (auto& entry : scripts) entry.second = parse_migration_script(resources.at({ResourceType::script,entry.first}));
    return scripts;
}
void adapt_parser(Resources& resources) {
    if (resources.count({ResourceType::vocab,10}) || resources.count({ResourceType::vocab,910}) || resources.count({ResourceType::vocab,911}))
        throw std::runtime_error("parser migration: secondary-language vocabularies require a separate conversion");
    const auto source = resources.find({ResourceType::vocab,0});
    const auto grammar = resources.find({ResourceType::vocab,900});
    if (source == resources.end() || grammar == resources.end())
        throw std::runtime_error("parser migration requires SCI0 word vocabulary 0 and grammar vocabulary 900");
    if (grammar->second.payload.empty() || grammar->second.payload.size()%20)
        throw std::runtime_error("parser migration: grammar must contain complete 20-byte rules");
    if (resources.count({ResourceType::vocab,902}))
        throw std::runtime_error("parser migration: vocabulary 902 conflicts with the target suffix resource");
    // SCI0 keeps the final definition of a repeated spelling. SCI1 supports
    // ambiguity, so collapse duplicates explicitly to retain SCI0 semantics.
    std::map<std::string,Word> words;
    for (const auto& entry : read_sci0_vocabulary(source->second.payload)) words[entry.text] = entry;
    if (words.empty()) throw std::runtime_error("parser migration: word vocabulary is empty");
    Bytes converted(510,0); // 255 little-endian initial-character offsets.
    for (const auto& entry : words) {
        const auto& word_entry = entry.second;
        if (word_entry.text.empty() || word_entry.text.size() > 254)
            throw std::runtime_error("parser migration: unsupported word length");
        const auto initial = static_cast<unsigned char>(word_entry.text.front());
        if (initial == 0 || initial == 255 || converted.size()+word_entry.text.size()+5 > 65531)
            throw std::runtime_error("parser migration: vocabulary exceeds SCI1 limits");
        if (word(converted,2*initial,510) == 0) patch(converted,2*initial,static_cast<unsigned>(converted.size()));
        converted.push_back(0); // Full spelling, no preceding-word prefix.
        converted.insert(converted.end(),word_entry.text.begin(),word_entry.text.end());
        converted.push_back(0);
        converted.push_back(static_cast<std::uint8_t>(word_entry.word_class >> 4));
        converted.push_back(static_cast<std::uint8_t>((word_entry.word_class << 4) | (word_entry.group >> 8)));
        converted.push_back(static_cast<std::uint8_t>(word_entry.group));
    }
    const auto suffix = resources.find({ResourceType::vocab,901});
    if (suffix != resources.end()) {
        auto moved = suffix->second;
        moved.entry.id.number = 902;
        resources.erase(suffix);
        resources.emplace(std::make_pair(ResourceType::vocab,std::uint16_t(902)),std::move(moved));
    }
    auto moved_grammar = grammar->second;
    moved_grammar.entry.id.number = 901;
    resources.erase(grammar);
    resources.emplace(std::make_pair(ResourceType::vocab,std::uint16_t(901)),std::move(moved_grammar));
    auto moved_words = source->second;
    moved_words.entry.id.number = 900;
    moved_words.payload = std::move(converted);
    resources.erase(source);
    resources.emplace(std::make_pair(ResourceType::vocab,std::uint16_t(900)),std::move(moved_words));
    // SCI0's debug kernel-name table describes the old ABI and also makes
    // ScummVM detect SCI0. SCI1 permits its absence and uses the standard ABI.
    resources.erase({ResourceType::vocab,999});
    bool view_present = false;
    for (const auto& entry : resources) if (entry.first.first == ResourceType::view) {
        (void)read_sci0_view(entry.second.payload);
        if (entry.first.second < 1000) view_present = true;
    }
    if (!view_present) throw std::runtime_error("SCI1 EGA parser migration requires a valid EGA view for interpreter detection");
}
// Expand the original main export table and relocate absolute addresses. Code
// references are relative, so an equal shift of instruction and target cancels.
// Unsupported source targets are rejected by strict parsing before relocation.
Bytes add_file_bridges(const Bytes& original, const ParsedScript& parsed, unsigned first_export) {
    const Section* table = nullptr;
    for (const auto& section : parsed.sections) if (section.type == sci_vm::section::exports) {
        if (table) throw std::runtime_error("migration requires a single main export table");
        table = &section;
    }
    if (!table) throw std::runtime_error("main script has no export table");
    constexpr unsigned added = kernel0::removed_file_functions * sci_vm::word_bytes;
    const auto threshold = table->end;
    auto moved = [&](unsigned offset) {
        return offset >= threshold && offset < original.size() ? offset+added : offset;
    };
    Bytes bytes(original.begin(), original.begin()+static_cast<std::ptrdiff_t>(threshold));
    bytes.insert(bytes.end(), added, 0);
    const auto last = parsed.sections.back().end;
    bytes.insert(bytes.end(), original.begin()+static_cast<std::ptrdiff_t>(threshold), original.begin()+static_cast<std::ptrdiff_t>(last));
    if (bytes.size()+64 > 65535) throw std::runtime_error("main script has insufficient space for file-I/O bridges");
    patch(bytes, table->start+2, static_cast<unsigned>(table->end-table->start)+added);
    patch(bytes, table->start+4, first_export+4);
    for (const auto& entry : parsed.exports) patch(bytes, moved(static_cast<unsigned>(entry.first)), moved(entry.second));
    for (const auto& object : parsed.objects) {
        auto address_table = object.pointer + 2*object.values.size() + 2*object.selectors.size() + 4 + 2*object.methods.size();
        for (std::size_t i = 0; i < object.addresses.size(); ++i)
            patch(bytes, moved(static_cast<unsigned>(address_table+2*i)), moved(object.addresses[i]));
        // Name pointers are metadata even if the compiler omitted relocation.
        if (object.values.size() > 3) patch(bytes, moved(static_cast<unsigned>(object.pointer+6)), moved(object.values[3]));
    }
    for (const auto& section : parsed.sections) if (section.type == sci_vm::section::relocations) {
        auto count = word(original, section.start+4, section.end);
        for (unsigned i = 0; i < count; ++i) {
            auto entry = section.start+6+i*2;
            auto slot = word(original, entry, section.end);
            patch(bytes, moved(static_cast<unsigned>(entry)), moved(slot));
            patch(bytes, moved(slot), moved(word(original, slot, original.size())));
        }
    }
    for (const auto& inst : parsed.instructions) if (inst.opcode == op::load_offset_to_accumulator || inst.opcode == op::load_offset_to_stack || inst.opcode == op::call_local || op::is_branch(inst.opcode)) {
        auto target_offset = target(inst);
        auto delta = static_cast<std::uint16_t>(moved(target_offset)-moved(static_cast<unsigned>(inst.end)));
        auto slot = moved(static_cast<unsigned>(inst.start+1));
        if (inst.width == 1) {
            auto signed_delta = static_cast<std::int16_t>(delta);
            if (signed_delta < -128 || signed_delta > 127) throw std::runtime_error("main relocation requires widening an instruction; unsupported");
            bytes.at(slot) = static_cast<std::uint8_t>(delta);
        } else patch(bytes, slot, delta);
    }
    // FileIO suboperations use exactly the same ScummVM implementations as
    // SCI0 FOpen/FPuts/FGets/FClose. Bridges preserve argument order and result.
    constexpr std::array<unsigned,4> subops{sci_vm::file_io::open,sci_vm::file_io::write_string,
                                          sci_vm::file_io::read_string,sci_vm::file_io::close};
    Bytes code;
    for (unsigned i = 0; i < 4; ++i) {
        patch(bytes, threshold+i*2, static_cast<unsigned>(bytes.size()+4+code.size()));
        // Add the FileIO suboperation, then forward the caller's entire actual
        // parameter list. This also preserves SCI0 &rest forwarding and malformed
        // legacy calls without reading nonexistent parameters or guessing defaults.
        const bool preserve_accumulator = subops[i] == sci_vm::file_io::close;
        if (preserve_accumulator) {
            append_byte_instruction(code,op::allocate_temporaries,{1});
            append_byte_instruction(code,op::store_accumulator_to_temporary,{0});
        }
        append_byte_instruction(code,op::push_one,{});
        append_byte_instruction(code,op::push_immediate,{subops[i]});
        append_byte_instruction(code,op::rest,{1});
        append_byte_instruction(code,op::call_kernel,{sci_vm::sci1_kernel::file_io,sci_vm::word_bytes});
        if (preserve_accumulator) append_byte_instruction(code,op::load_temporary_to_accumulator,{0});
        append_byte_instruction(code,op::return_,{});
    }
    put(bytes, sci_vm::section::code); put(bytes, static_cast<unsigned>(code.size()+sci_vm::section_header_bytes));
    bytes.insert(bytes.end(), code.begin(), code.end()); put(bytes, 0);
    return bytes;
}
std::vector<std::string> repair_volume_queries(Resources& resources) {
    std::vector<std::string> repaired;
    for (auto& entry : resources) if (entry.first.first == ResourceType::script) {
        auto& resource = entry.second;
        const auto script = parse_migration_script(resource);
        for (std::size_t i = 0; i < script.instructions.size(); ++i) {
            const auto frame = migration_detail::volume_query_frame(script,i);
            if (!frame) continue;
            const auto& [count,parameter,call] = *frame;
            if (!migration_detail::uninitialized_temporary(script,parameter.operands.at(0),parameter.start)) continue;
            auto& payload = resource.payload;
            payload.at(count.start) = static_cast<std::uint8_t>(sci_vm::encoded_opcode(op::push_one));
            payload.at(parameter.start) = static_cast<std::uint8_t>(sci_vm::encoded_opcode(op::jump,parameter.width == 1));
            for (unsigned byte = 0; byte < parameter.width; ++byte) payload.at(parameter.start+1+byte) = 0;
            payload.at(call.end-1) = sci_vm::word_bytes;
            repaired.push_back("Repaired invalid master-volume setter as a query: script " + std::to_string(entry.first.second) +
                " at byte " + std::to_string(call.start) + ", uninitialized temporary " + std::to_string(parameter.operands.at(0)) + ".\n");
        }
    }
    return repaired;
}


Resources resolve_duplicate_resources(const Game& game) {
    Resources unique;
    // SCI0 ScummVM lookup keeps the first map entry for duplicate IDs.
    for (const auto& entry : index_resources(game)) unique.emplace(entry.first, *entry.second);
    return unique;
}

unsigned validate_main_export(const ScriptMetadata& script_metadata) {
    if (!script_metadata.count(0)) throw std::runtime_error("migration requires script 0");
    const auto& parsed_main = script_metadata.at(0);
    if (parsed_main.exports.empty()) throw std::runtime_error("migration requires main export 0");
    bool main_object = false;
    for (const auto& object : parsed_main.objects)
        if (object.pointer == parsed_main.exports.front().second) main_object = true;
    if (!main_object) throw std::runtime_error("main export 0 must identify a decoded object");
    auto first_export = static_cast<unsigned>(parsed_main.exports.size());
    if (first_export > 252) throw std::runtime_error("main export table cannot accommodate four byte-sized file-I/O bridges");
    return first_export;
}

void write_first_operand(Bytes& payload, const Instruction& instruction, unsigned value) {
    if (instruction.width == sci_vm::word_bytes) {
        patch(payload,instruction.start+1,value);
        return;
    }
    if (value > 255) throw std::runtime_error("rewritten byte operand exceeds VM encoding");
    payload.at(instruction.start+1) = static_cast<std::uint8_t>(value);
}

void record_legacy_metadata(const Resource& resource, const ParsedScript& script, MigrationStats& stats) {
    for (const auto& instruction : script.instructions)
        if (op::is_branch(instruction.opcode) && !script.boundaries.count(target(instruction)))
            stats.legacy_branches.push_back("script " + std::to_string(resource.entry.id.number) + " at byte " +
                std::to_string(instruction.start) + " -> " + std::to_string(target(instruction)));
    for (const auto& exported : script.exports)
        if (exported.second && !script.boundaries.count(exported.second) && !script.object_pointers.count(exported.second))
            ++stats.opaque_exports;
}

void rewrite_file_call(Resource& resource, const Instruction& instruction, unsigned first_export, MigrationStats& stats) {
    constexpr std::array<unsigned,4> expected_frame_bytes{4,4,6,2};
    const auto bridge = instruction.operands.at(0)-kernel0::file_open;
    const auto frame = instruction.operands.at(1);
    if (frame % sci_vm::word_bytes)
        throw std::runtime_error("script " + std::to_string(resource.entry.id.number) + " at byte " +
            std::to_string(instruction.start) + ": odd SCI0 file-I/O argument-frame size");
    if (frame != expected_frame_bytes.at(bridge)) ++stats.unusual_file_frames;
    auto& payload = resource.payload;
    payload.at(instruction.start) = static_cast<std::uint8_t>((op::call_base << 1) | (payload.at(instruction.start) & 1u));
    write_first_operand(payload,instruction,first_export+bridge);
    ++stats.bridged;
}

void rewrite_kernel_call(Resource& resource, const ParsedScript& script, std::size_t index,
                         const Game& game, unsigned first_export, bool& sound_dispatch_checked, MigrationStats& stats) {
    const auto& instruction = script.instructions.at(index);
    const auto kernel = instruction.operands.at(0);
    if (kernel >= kernel0::parse && kernel <= kernel0::set_synonyms) {
        const auto expected = kernel == kernel0::parse ? 4u : 2u;
        if (instruction.operands.at(1) != expected)
            throw std::runtime_error("unsupported parser migration argument frame in script " + std::to_string(resource.entry.id.number));
        ++stats.parser_calls;
    }
    if (kernel == kernel0::do_sound) {
        if (!sound_dispatch_checked) {
            validate_sound_dispatch(game);
            sound_dispatch_checked = true;
        }
        try { validate_sound_call(script,index); }
        catch (const std::exception& error) {
            throw std::runtime_error("script " + std::to_string(resource.entry.id.number) + ": " + error.what());
        }
        ++stats.sound_calls;
    }
    if (kernel > kernel0::last)
        throw std::runtime_error("unsupported SCI0 kernel ID in script " + std::to_string(resource.entry.id.number));
    if (kernel == kernel0::do_avoider)
        throw std::runtime_error("SCI0 DoAvoider requires a semantic port; migration refused");
    if (kernel >= kernel0::file_open && kernel <= kernel0::file_close) {
        rewrite_file_call(resource,instruction,first_export,stats);
    } else if (kernel > kernel0::file_close) {
        write_first_operand(resource.payload,instruction,kernel-kernel0::removed_file_functions);
        ++stats.remapped;
    }
}

MigrationStats rewrite_script_kernels(Resources& unique, const ScriptMetadata& script_metadata,
                                      const Game& game, unsigned first_export) {
    MigrationStats stats;
    bool sound_dispatch_checked = false;
    for (auto& entry : unique) if (entry.first.first == ResourceType::script) {
        ++stats.scripts;
        const auto& parsed = script_metadata.at(entry.first.second);
        record_legacy_metadata(entry.second,parsed,stats);
        for (std::size_t instruction_index = 0; instruction_index < parsed.instructions.size(); ++instruction_index) {
            const auto& inst = parsed.instructions[instruction_index];
            if (inst.opcode != op::call_kernel) continue;
            rewrite_kernel_call(entry.second,parsed,instruction_index,game,first_export,sound_dispatch_checked,stats);
        }
    }
    return stats;
}

void append_main_file_bridges(Resources& resources, unsigned first_export) {
    auto& main = resources.at({ResourceType::script,0});
    // Reparse after remapping so main-relative operands and references are based
    // on the actual modified bytes before expanding the export table.
    main.payload = add_file_bridges(main.payload,parse_migration_script(main),first_export);
}

void verify_preserved_script_layouts(const Resources& unique, const ScriptMetadata& script_metadata) {
    // Enforce the invariant that makes preserving legacy branches possible.
    // Kernel/bridge rewrites are equal length, and no branch operands change.
    for (const auto& entry : unique) if (entry.first.first == ResourceType::script && entry.first.second != 0) {
        const auto after = parse_migration_script(entry.second);
        const auto& before = script_metadata.at(entry.first.second);
        if (after.boundaries != before.boundaries || after.instructions.size() != before.instructions.size())
            throw std::runtime_error("migration changed non-main script instruction layout");
        for (std::size_t i = 0; i < before.instructions.size(); ++i) {
            const auto& old_inst = before.instructions[i];
            const auto& new_inst = after.instructions[i];
            if (old_inst.end != new_inst.end || (op::is_branch(old_inst.opcode) &&
                (old_inst.opcode != new_inst.opcode || old_inst.operands != new_inst.operands)))
                throw std::runtime_error("migration changed a preserved branch operand or instruction extent");
        }
    }
}

std::vector<Resource> take_resources(Resources& resources) {
    std::vector<Resource> output;
    output.reserve(resources.size());
    for (auto& entry : resources) output.push_back(std::move(entry.second));
    return output;
}

GameFiles write_verified_game(const std::vector<Resource>& output, Sci1Format format) {
    auto files = write_sci1_game(output,format);
    const auto reopened = read_sci1_game(files,format);
    if (reopened.resources.size() != output.size()) throw std::runtime_error("migration resource count verification failed");
    for (std::size_t i = 0; i < output.size(); ++i)
        if (reopened.resources[i].entry.id.type != output[i].entry.id.type ||
            reopened.resources[i].entry.id.number != output[i].entry.id.number ||
            reopened.resources[i].payload != output[i].payload)
            throw std::runtime_error("migration container round-trip verification failed");
    return files;
}

